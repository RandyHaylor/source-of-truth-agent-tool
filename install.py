#!/usr/bin/env python3
"""
Cross-platform installer for source-of-truth-agent-tool.

What it does (idempotent):
  1. Resolves the install dir at ~/.claude/skills/source-of-truth-agent-tool/.
     (Putting it under skills/ means Claude Code auto-discovers SKILL.md.)
  2. Copies the entire repo's contents (source_of_truth/ package, SKILL.md,
     project-start-wizard.md, README.md, etc.) into the install dir.
     EDGE CASE: if the user already cloned directly into the install dir
     and is running install.py from there, the copy step is silently
     skipped -- nothing to copy.
  3. Writes two wrapper scripts in the install dir:
       - user_prompt_submit_hook.py
       - post_tool_use_hook.py
     Each adds the install dir to sys.path and calls into the source_of_truth
     package next to it. On any error they silently emit {} so unrelated
     sessions never see import errors.
  4. Patches ~/.claude/settings.json to register both hooks if not already
     present. Existing hook entries are left untouched. Backed up first.
  5. Initializes ~/.source-of-truth/ with default global-settings.json.

Run:
  python3 install.py           # Linux/macOS
  python install.py            # Windows
"""
import datetime
import json
import os
import platform
import shutil


SKILL_INSTALL_DIR_NAME = "source-of-truth-agent-tool"
USER_PROMPT_SUBMIT_HOOK_FILENAME = "user_prompt_submit_hook.py"
POST_TOOL_USE_HOOK_FILENAME = "post_tool_use_hook.py"
ASKUSERQUESTION_CAPTURE_HOOK_FILENAME = "post_tool_use_askuserquestion_capture_hook.py"
WHAT_IS_SESSION_HOOK_FILENAME = "what_is_session_id_hook.py"
WHAT_IS_SESSION_SENTINEL_FILENAME = "WhatIsTheCurrentSessionId.txt"
WHAT_IS_SESSION_SENTINEL_STRING = "WhatIsTheCurrentSessionId"

USER_PROMPT_SUBMIT_HOOK_TEMPLATE = '''\
#!/usr/bin/env python3
"""Auto-generated by source-of-truth-agent-tool install.py."""
import sys
PACKAGE_DIRECTORY_ABSOLUTE_PATH = {package_dir!r}
def _emit_empty_and_exit_silently():
    print("{{}}")
    sys.exit(0)
def _main():
    try:
        sys.path.insert(0, PACKAGE_DIRECTORY_ABSOLUTE_PATH)
        from source_of_truth.cli_entrypoint import _handle_user_prompt_submit_hook
    except Exception:
        _emit_empty_and_exit_silently(); return
    try:
        sys.exit(_handle_user_prompt_submit_hook())
    except Exception:
        _emit_empty_and_exit_silently()
if __name__ == "__main__":
    _main()
'''

WHAT_IS_SESSION_HOOK_TEMPLATE = '''\
#!/usr/bin/env python3
"""Auto-generated by source-of-truth-agent-tool install.py.

Standalone PostToolUse hook. Does nothing unless the tool_input of the
just-completed tool call contains the sentinel string {sentinel_string!r}.
When it does, emit a hookSpecificOutput that surfaces the current session_id
to both the user (as systemMessage) and the agent (as additionalContext).

Self-contained: no imports from source_of_truth package, so it works even
if that package is broken or absent. On any error, silently emit {{}} so
unrelated sessions never see noise.
"""
import json
import sys

SENTINEL_SUBSTRING = {sentinel_string!r}


def _emit_empty_and_exit_silently():
    print("{{}}")
    sys.exit(0)


def _tool_input_mentions_sentinel(tool_input_value):
    try:
        serialized_form = json.dumps(tool_input_value, ensure_ascii=False)
    except Exception:
        serialized_form = str(tool_input_value)
    return SENTINEL_SUBSTRING in serialized_form


def _main():
    try:
        raw_stdin_payload = sys.stdin.read()
        if not raw_stdin_payload.strip():
            _emit_empty_and_exit_silently(); return
        hook_event_payload = json.loads(raw_stdin_payload)
    except Exception:
        _emit_empty_and_exit_silently(); return

    tool_input_value = hook_event_payload.get("tool_input")
    if tool_input_value is None or not _tool_input_mentions_sentinel(tool_input_value):
        _emit_empty_and_exit_silently(); return

    current_session_id = hook_event_payload.get("session_id", "<unknown>")
    user_visible_and_agent_visible_message = f"Current session id: {{current_session_id}}"

    response_payload_for_claude_code = {{
        "hookSpecificOutput": {{
            "hookEventName": "PostToolUse",
            "additionalContext": user_visible_and_agent_visible_message,
        }},
        "systemMessage": user_visible_and_agent_visible_message,
    }}
    print(json.dumps(response_payload_for_claude_code))
    sys.exit(0)


if __name__ == "__main__":
    try:
        _main()
    except Exception:
        _emit_empty_and_exit_silently()
'''

