def home_claude_dir():
    return os.path.expanduser("~/.claude")


def home_skills_dir():
    return os.path.join(home_claude_dir(), "skills")


def install_dir_path():
    return os.path.join(home_skills_dir(), SKILL_INSTALL_DIR_NAME)


def settings_json_path():
    return os.path.join(home_claude_dir(), "settings.json")


def python_launcher_for_current_platform():
    return "python" if platform.system() == "Windows" else "python3"


def is_running_from_install_dir(repo_dir, install_dir):
    return os.path.realpath(repo_dir) == os.path.realpath(install_dir)


def back_up_existing_install_dir_by_moving_it(install_dir):
    """Move an existing install dir to a timestamped backup, never delete it.

    Backup location:
        ~/.claude/source-of-truth-bak/<UTC-timestamp>/source-of-truth-agent-tool/

    This makes a reinstall non-destructive by default: the whole old folder
    (including anything a user may have placed in it) is preserved, not wiped.
    Returns the backup path, or None if there was no existing dir to move.
    """
    if not os.path.isdir(install_dir):
        return None
    timestamp = datetime.datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    backup_parent_dir = os.path.join(home_claude_dir(), "source-of-truth-bak", timestamp)
    backup_dir = os.path.join(backup_parent_dir, SKILL_INSTALL_DIR_NAME)
    os.makedirs(backup_parent_dir, exist_ok=True)
    shutil.move(install_dir, backup_dir)
    return backup_dir


def copy_repo_contents_into_install_dir(repo_dir, install_dir):
    """Deploy the repo into the install dir.

    Skips .git/, .claude/, __pycache__/, *.pyc, and any *.bak* settings backups
    that might happen to be under the repo (defensive). .claude/ is session-local
    Claude Code state (settings, plans, hooks) -- never part of the deployable
    tool. Any existing install dir is NOT deleted -- it is moved to a timestamped
    backup first (so renamed/removed files don't linger AND nothing is ever
    destroyed), then the repo is copied in fresh.
    """
    ignore_patterns_callable = shutil.ignore_patterns(
        ".git", ".claude", "__pycache__", "*.pyc", "*.bak.*",
    )
    backup_dir = back_up_existing_install_dir_by_moving_it(install_dir)
    if backup_dir:
        print(
            "  NOTE: existing install dir preserved (not deleted); moved to backup:\n"
            f"    {backup_dir}"
        )
    shutil.copytree(repo_dir, install_dir, ignore=ignore_patterns_callable)
    print(f"  copied repo -> {install_dir}")


def load_or_init_settings_json(path):
    if not os.path.isfile(path):
        return {}
    with open(path) as f:
        content = f.read().strip()
    return json.loads(content) if content else {}


def remove_stale_source_of_truth_hook_entries(
    settings_data, hook_event_name, install_dir_canonical
):
    """Remove any pre-existing hook entries that mention SKILL_INSTALL_DIR_NAME
    but do NOT point at the current install_dir. This is the duplicate-prevention
    guard: install.py never adds an entry alongside a stale one for the same tool.

    Returns count of removed entries.
    """
    hooks_root = settings_data.get("hooks")
    if not isinstance(hooks_root, dict):
        return 0
    event_list = hooks_root.get(hook_event_name)
    if not isinstance(event_list, list):
        return 0
    removed_count = 0
    surviving_matcher_entries = []
    for matcher_entry in event_list:
        inner_hooks = matcher_entry.get("hooks", [])
        filtered_inner_hooks = []
        for hook_item in inner_hooks:
            command_text = hook_item.get("command", "")
            mentions_our_tool = SKILL_INSTALL_DIR_NAME in command_text
            points_at_current_install = install_dir_canonical in command_text
            if mentions_our_tool and not points_at_current_install:
                removed_count += 1
                continue
            filtered_inner_hooks.append(hook_item)
        if filtered_inner_hooks:
            matcher_entry["hooks"] = filtered_inner_hooks
            surviving_matcher_entries.append(matcher_entry)
    if surviving_matcher_entries:
        hooks_root[hook_event_name] = surviving_matcher_entries
    else:
        hooks_root.pop(hook_event_name, None)
        if not hooks_root:
            settings_data.pop("hooks", None)
    return removed_count


def remove_all_source_of_truth_hook_entries_for_event(settings_data, hook_event_name):
    """Remove EVERY hook entry for an event that mentions this tool, regardless of
    path. Used to retire a hook event the tool no longer uses (the Stop hook).
    Returns the count of removed entries."""
    hooks_root = settings_data.get("hooks")
    if not isinstance(hooks_root, dict):
        return 0
    event_list = hooks_root.get(hook_event_name)
    if not isinstance(event_list, list):
        return 0
    removed_count = 0
    surviving_matcher_entries = []
    for matcher_entry in event_list:
        kept_inner_hooks = []
        for hook_item in matcher_entry.get("hooks", []):
            if SKILL_INSTALL_DIR_NAME in hook_item.get("command", ""):
                removed_count += 1
                continue
            kept_inner_hooks.append(hook_item)
        if kept_inner_hooks:
            matcher_entry["hooks"] = kept_inner_hooks
            surviving_matcher_entries.append(matcher_entry)
    if surviving_matcher_entries:
        hooks_root[hook_event_name] = surviving_matcher_entries
    else:
        hooks_root.pop(hook_event_name, None)
        if not hooks_root:
            settings_data.pop("hooks", None)
    return removed_count


def hook_event_already_has_entry_for_install_dir(settings_data, hook_event_name, install_dir_canonical):
    entries = settings_data.get("hooks", {}).get(hook_event_name, [])
    for matcher_entry in entries:
        for hook_item in matcher_entry.get("hooks", []):
            if install_dir_canonical in hook_item.get("command", ""):
                return True
    return False


def append_hook_entry(settings_data, hook_event_name, matcher, command):
    hooks_root = settings_data.setdefault("hooks", {})
    event_list = hooks_root.setdefault(hook_event_name, [])
    event_list.append({
        "matcher": matcher,
        "hooks": [{"type": "command", "command": command}],
    })


def backup_file(path):
    if not os.path.isfile(path):
        return None
    timestamp = datetime.datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    backup_path = f"{path}.bak.{timestamp}"
    shutil.copyfile(path, backup_path)
    return backup_path


def write_settings_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")


def write_wrapper_scripts(install_dir):
    os.makedirs(install_dir, exist_ok=True)
    user_hook_path = os.path.join(install_dir, USER_PROMPT_SUBMIT_HOOK_FILENAME)
    post_hook_path = os.path.join(install_dir, POST_TOOL_USE_HOOK_FILENAME)
    askuserquestion_capture_hook_path = os.path.join(install_dir, ASKUSERQUESTION_CAPTURE_HOOK_FILENAME)
    what_is_session_hook_path = os.path.join(install_dir, WHAT_IS_SESSION_HOOK_FILENAME)
    sentinel_txt_path = os.path.join(install_dir, WHAT_IS_SESSION_SENTINEL_FILENAME)

    with open(user_hook_path, "w") as f:
        f.write(USER_PROMPT_SUBMIT_HOOK_TEMPLATE.format(package_dir=install_dir))
    with open(post_hook_path, "w") as f:
        f.write(POST_TOOL_USE_HOOK_TEMPLATE.format(package_dir=install_dir))
    with open(askuserquestion_capture_hook_path, "w") as f:
        f.write(ASKUSERQUESTION_CAPTURE_HOOK_TEMPLATE.format(package_dir=install_dir))
    with open(what_is_session_hook_path, "w") as f:
        f.write(WHAT_IS_SESSION_HOOK_TEMPLATE.format(
            sentinel_string=WHAT_IS_SESSION_SENTINEL_STRING,
        ))
    with open(sentinel_txt_path, "w", encoding="utf-8") as f:
        f.write(
            "If source-of-truth is installed, its hook will echo the "
            "current session id to the user notification and the "
            "additionalContext whenever a tool call's input mentions the "
            "string WhatIsTheCurrentSessionId. Read or cat this file to "
            "trigger that.\n"
        )

    if platform.system() != "Windows":
        os.chmod(user_hook_path, 0o755)
        os.chmod(post_hook_path, 0o755)
        os.chmod(askuserquestion_capture_hook_path, 0o755)
        os.chmod(what_is_session_hook_path, 0o755)
    print(f"  wrote: {user_hook_path}")
    print(f"  wrote: {post_hook_path}")
    print(f"  wrote: {askuserquestion_capture_hook_path}")
    print(f"  wrote: {what_is_session_hook_path}")
    print(f"  wrote: {sentinel_txt_path}")
    return user_hook_path, post_hook_path, what_is_session_hook_path


SOURCE_OF_TRUTH_WRAPPER_SCRIPT_NAME_POSIX = "source-of-truth"
