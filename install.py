WINDOWS_PATH_STUB_TEMPLATE = '''\
@echo off
REM Auto-generated by source-of-truth-agent-tool install.py.
REM Forwards to the canonical wrapper inside the skill folder.
call {skill_folder_wrapper_quoted} %*
'''


def write_skill_folder_source_of_truth_wrapper(install_dir):
    """Write the canonical `source-of-truth` wrapper script inside the skill folder.

    This is the script the PATH stub forwards to. Lives next to the package code
    so the skill folder is fully self-contained.
    """
    if platform.system() == "Windows":
        wrapper_filename = SOURCE_OF_TRUTH_WRAPPER_SCRIPT_NAME_WINDOWS
        template = WINDOWS_SKILL_FOLDER_WRAPPER_TEMPLATE
    else:
        wrapper_filename = SOURCE_OF_TRUTH_WRAPPER_SCRIPT_NAME_POSIX
        template = POSIX_SKILL_FOLDER_WRAPPER_TEMPLATE
    wrapper_path = os.path.join(install_dir, wrapper_filename)
    with open(wrapper_path, "w") as f:
        f.write(template.format(install_dir_quoted=repr(install_dir)))
    if platform.system() != "Windows":
        os.chmod(wrapper_path, 0o755)
    print(f"  wrote skill-folder wrapper -> {wrapper_path}")
    return wrapper_path


def path_stub_target_directory_for_current_platform():
    """Return the dir where install.py should write the on-PATH stub.

    Linux/macOS: ~/.local/bin (Python community convention; usually on PATH).
    Windows:    %USERPROFILE%\\AppData\\Local\\Microsoft\\WindowsApps
                (per-user, on PATH by default in Windows 10+, no admin rights).
    """
    if platform.system() == "Windows":
        return os.path.join(
            os.path.expanduser("~"),
            "AppData", "Local", "Microsoft", "WindowsApps",
        )
    return os.path.join(os.path.expanduser("~"), ".local", "bin")


def write_path_stub_forwarding_to_skill_folder_wrapper(skill_folder_wrapper_path):
    """Write a tiny stub on PATH that forwards to the skill-folder wrapper.

    Returns (stub_path, target_dir_was_already_on_PATH).
    """
    target_dir = path_stub_target_directory_for_current_platform()
    os.makedirs(target_dir, exist_ok=True)
    if platform.system() == "Windows":
        stub_filename = SOURCE_OF_TRUTH_WRAPPER_SCRIPT_NAME_WINDOWS
        template = WINDOWS_PATH_STUB_TEMPLATE
        # cmd.exe does not honor single quotes; wrap with double quotes instead.
        wrapper_quoted = '"' + skill_folder_wrapper_path.replace('"', '""') + '"'
    else:
        stub_filename = SOURCE_OF_TRUTH_WRAPPER_SCRIPT_NAME_POSIX
        template = POSIX_PATH_STUB_TEMPLATE
        wrapper_quoted = repr(skill_folder_wrapper_path)
    stub_path = os.path.join(target_dir, stub_filename)
    with open(stub_path, "w", encoding="utf-8") as f:
        f.write(template.format(skill_folder_wrapper_quoted=wrapper_quoted))
    if platform.system() != "Windows":
        os.chmod(stub_path, 0o755)
    print(f"  wrote PATH stub -> {stub_path}")

    # Best-effort PATH check.
    path_environment_value = os.environ.get("PATH", "")
    path_separator_for_platform = ";" if platform.system() == "Windows" else ":"
    on_path_already = os.path.realpath(target_dir) in [
        os.path.realpath(p) for p in path_environment_value.split(path_separator_for_platform)
        if p
    ]
    if not on_path_already:
        print(
            f"  NOTE: {target_dir} is not currently on your PATH. "
            "Add it to invoke `source-of-truth` from anywhere; "
            "otherwise call the skill-folder wrapper directly."
        )
    return stub_path


def initialize_global_settings_file():
    """Create ~/.source-of-truth/global-settings.json with defaults if absent."""
    sot_root = os.path.expanduser("~/.source-of-truth")
    global_settings_path = os.path.join(sot_root, "global-settings.json")
    os.makedirs(sot_root, exist_ok=True)
    os.makedirs(os.path.join(sot_root, "projects"), exist_ok=True)
    if os.path.isfile(global_settings_path):
        print(f"  global settings already present at {global_settings_path}")
        return
    default_payload = {
        "reviewer_command": ["claude", "-p"],
        "reviewer_mode": "live",
        "reviewer_model_name": "claude-haiku-4-5-20251001",
    }
    with open(global_settings_path, "w") as f:
        json.dump(default_payload, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"  wrote default global settings -> {global_settings_path}")


def ensure_settings_json_hook_entries(install_dir, settings_path, python_launcher):
    """Idempotently ensure ~/.claude/settings.json has the four SoT hook entries
    pointing at install_dir; scrub stale entries pointing elsewhere. Returns True
    if settings.json was modified. Reused by main() and the register-time health
    check, so the hook-registration logic lives in exactly one place."""
    user_hook_path = os.path.join(install_dir, USER_PROMPT_SUBMIT_HOOK_FILENAME)
    post_hook_path = os.path.join(install_dir, POST_TOOL_USE_HOOK_FILENAME)
    askuserquestion_capture_hook_path = os.path.join(install_dir, ASKUSERQUESTION_CAPTURE_HOOK_FILENAME)
    what_is_session_hook_path = os.path.join(install_dir, WHAT_IS_SESSION_HOOK_FILENAME)

    settings_data = load_or_init_settings_json(settings_path)
    user_command = f'{python_launcher} "{user_hook_path}"'
    post_command = f'{python_launcher} "{post_hook_path}"'
    askuserquestion_capture_command = f'{python_launcher} "{askuserquestion_capture_hook_path}"'
    what_is_session_command = f'{python_launcher} "{what_is_session_hook_path}"'

    settings_was_modified = False

    # Duplicate-prevention guard: scrub any pre-existing entries that mention
    # this tool but do NOT point at the current install dir. Catches stale
    # entries from a previous install at a different path (e.g. an older
    # version of install.py that used a different layout).
    removed_user = remove_stale_source_of_truth_hook_entries(
        settings_data, "UserPromptSubmit", install_dir
    )
    removed_post = remove_stale_source_of_truth_hook_entries(
        settings_data, "PostToolUse", install_dir
    )
    if removed_user + removed_post:
        print(f"  removed {removed_user} stale UserPromptSubmit + "
              f"{removed_post} stale PostToolUse entries pointing elsewhere")
        settings_was_modified = True

    # Retire the old Stop hook entirely: pre-text is now captured by the
    # UserPromptSubmit hook (which fires even when a turn is interrupted), so the
    # Stop hook is obsolete. Remove ANY SoT Stop entry left from a prior install.
    removed_stop = remove_all_source_of_truth_hook_entries_for_event(settings_data, "Stop")
    if removed_stop:
        print(f"  removed {removed_stop} obsolete Stop entr(y/ies) "
              f"(pre-text capture moved to UserPromptSubmit)")
        settings_was_modified = True

    if hook_event_already_has_entry_for_install_dir(settings_data, "UserPromptSubmit", install_dir):
        print("  UserPromptSubmit entry already present -- no change")
    else:
        append_hook_entry(settings_data, "UserPromptSubmit", "*", user_command)
        print(f"  appended UserPromptSubmit: {user_command}")
        settings_was_modified = True

    # Two distinct PostToolUse hooks both point at install_dir, so
    # hook_event_already_has_entry_for_install_dir can't tell them apart.
    # Match each command explicitly instead.
    existing_post_commands_in_settings = [
        hook_item.get("command", "")
        for matcher_entry in settings_data.get("hooks", {}).get("PostToolUse", [])
        for hook_item in matcher_entry.get("hooks", [])
    ]
    if post_command not in existing_post_commands_in_settings:
        append_hook_entry(settings_data, "PostToolUse", "Bash", post_command)
        print(f"  appended PostToolUse(matcher=Bash): {post_command}")
        settings_was_modified = True
    else:
        print("  PostToolUse (SoT) entry already present -- no change")
    if askuserquestion_capture_command not in existing_post_commands_in_settings:
        append_hook_entry(settings_data, "PostToolUse", "AskUserQuestion", askuserquestion_capture_command)
        print(f"  appended PostToolUse(matcher=AskUserQuestion): {askuserquestion_capture_command}")
        settings_was_modified = True
    else:
        print("  PostToolUse (AskUserQuestion capture) entry already present -- no change")
    if what_is_session_command not in existing_post_commands_in_settings:
        append_hook_entry(settings_data, "PostToolUse", "*", what_is_session_command)
        print(f"  appended PostToolUse(matcher=*) what-is-session: {what_is_session_command}")
        settings_was_modified = True
    else:
        print("  PostToolUse (what-is-session) entry already present -- no change")

    if settings_was_modified:
        backup_path = backup_file(settings_path)
        if backup_path:
            print(f"  backed up old settings.json to {backup_path}")
        write_settings_json(settings_path, settings_data)
    else:
        print("  no settings.json changes needed")
    return settings_was_modified


